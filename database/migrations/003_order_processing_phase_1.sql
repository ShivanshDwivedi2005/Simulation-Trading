ALTER TABLE orders
    ADD CONSTRAINT orders_status_check CHECK (status IN ('PENDING', 'OPEN', 'PARTIALLY_FILLED', 'FILLED', 'CANCELLED', 'REJECTED', 'EXPIRED')),
    ADD CONSTRAINT orders_order_type_check CHECK (order_type IN ('MARKET', 'LIMIT', 'STOP', 'STOP_LIMIT')),
    ADD CONSTRAINT orders_quantity_integer_check CHECK (quantity = trunc(quantity)),
    ADD CONSTRAINT orders_remaining_quantity_check CHECK (remaining_quantity >= 0 AND remaining_quantity <= quantity AND remaining_quantity = trunc(remaining_quantity)),
    ADD CONSTRAINT orders_limit_ticks_check CHECK (limit_price_ticks IS NULL OR limit_price_ticks > 0),
    ADD CONSTRAINT orders_stop_ticks_check CHECK (stop_price_ticks IS NULL OR stop_price_ticks > 0),
    ADD CONSTRAINT orders_required_limit_ticks_check CHECK (order_type NOT IN ('LIMIT', 'STOP_LIMIT') OR limit_price_ticks IS NOT NULL),
    ADD CONSTRAINT orders_required_stop_ticks_check CHECK (order_type NOT IN ('STOP', 'STOP_LIMIT') OR stop_price_ticks IS NOT NULL),
    ADD CONSTRAINT orders_trader_fk FOREIGN KEY (trader_id) REFERENCES users(trader_id);

CREATE UNIQUE INDEX IF NOT EXISTS orders_numeric_id_uidx ON orders (id);
CREATE UNIQUE INDEX IF NOT EXISTS orders_client_order_id_uidx ON orders (client_order_id);
CREATE UNIQUE INDEX IF NOT EXISTS orders_sequence_number_uidx ON orders (sequence_number);
CREATE INDEX IF NOT EXISTS orders_id_lookup_idx ON orders (id);
CREATE INDEX IF NOT EXISTS orders_trader_history_idx ON orders (trader_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS orders_active_instrument_idx ON orders (instrument_id, sequence_number)
    WHERE status IN ('PENDING', 'OPEN', 'PARTIALLY_FILLED');
CREATE INDEX IF NOT EXISTS orders_active_buy_limits_idx ON orders (instrument_id, limit_price_ticks DESC, sequence_number ASC)
    WHERE side = 'BUY' AND order_type IN ('LIMIT', 'STOP_LIMIT') AND status IN ('PENDING', 'OPEN', 'PARTIALLY_FILLED');
CREATE INDEX IF NOT EXISTS orders_active_sell_limits_idx ON orders (instrument_id, limit_price_ticks ASC, sequence_number ASC)
    WHERE side = 'SELL' AND order_type IN ('LIMIT', 'STOP_LIMIT') AND status IN ('PENDING', 'OPEN', 'PARTIALLY_FILLED');
CREATE INDEX IF NOT EXISTS orders_active_stops_idx ON orders (instrument_id, stop_price_ticks, sequence_number)
    WHERE order_type IN ('STOP', 'STOP_LIMIT') AND status IN ('PENDING', 'OPEN', 'PARTIALLY_FILLED');

CREATE TABLE IF NOT EXISTS executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id VARCHAR(128) NOT NULL UNIQUE,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    trader_id BIGINT NOT NULL REFERENCES users(trader_id),
    instrument_id BIGINT NOT NULL REFERENCES instruments(id),
    execution_price_ticks BIGINT NOT NULL CHECK (execution_price_ticks > 0),
    execution_quantity BIGINT NOT NULL CHECK (execution_quantity > 0),
    market_bid_ticks BIGINT CHECK (market_bid_ticks > 0),
    market_ask_ticks BIGINT CHECK (market_ask_ticks > 0),
    price_source VARCHAR(64) NOT NULL,
    market_timestamp TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS executions_order_idx ON executions (order_id, created_at, id);

CREATE TABLE IF NOT EXISTS order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(128) NOT NULL UNIQUE,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    event_type VARCHAR(64) NOT NULL,
    event_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS order_events_order_idx ON order_events (order_id, created_at, id);

