ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS trader_id BIGINT,
    ADD COLUMN IF NOT EXISTS limit_price_ticks BIGINT,
    ADD COLUMN IF NOT EXISTS stop_price_ticks BIGINT,
    ADD COLUMN IF NOT EXISTS sequence_number BIGINT DEFAULT nextval('order_sequence_number_seq');

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;
ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_order_type_check;

UPDATE orders o
SET trader_id = u.trader_id,
    limit_price_ticks = CASE WHEN o.limit_price IS NULL THEN NULL ELSE round(o.limit_price / i.tick_size)::BIGINT END,
    stop_price_ticks = CASE WHEN o.stop_price IS NULL THEN NULL ELSE round(o.stop_price / i.tick_size)::BIGINT END,
    sequence_number = COALESCE(o.sequence_number, nextval('order_sequence_number_seq'))
FROM users u, instruments i
WHERE o.user_id = u.user_id
  AND o.instrument_id = i.instrument_id
  AND (o.trader_id IS NULL OR o.sequence_number IS NULL OR
       (o.limit_price IS NOT NULL AND o.limit_price_ticks IS NULL) OR
       (o.stop_price IS NOT NULL AND o.stop_price_ticks IS NULL));

UPDATE orders SET status = 'PENDING' WHERE status = 'NEW';
UPDATE orders SET status = 'OPEN' WHERE status = 'ACCEPTED';

ALTER TABLE orders
    ALTER COLUMN trader_id SET NOT NULL,
    ALTER COLUMN sequence_number SET NOT NULL,
    ALTER COLUMN version SET DEFAULT 1;
UPDATE orders SET version = 1 WHERE version = 0;

